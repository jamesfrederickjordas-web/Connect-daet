import { NextRequest, NextResponse } from 'next/server';

interface BriefMetrics {
  recentArrivals: number;
  priorArrivals: number;
  growthRatePct: number | null;
  totalRevenuePhp: number;
  verifiedRevenuePct: number;
  employmentCount: number;
  satisfactionScore: number;
  satisfactionCount: number;
  watchIndicators: string[];
  topDestinations: { destination: string; total: number }[];
}

export async function POST(request: NextRequest) {
  try {
    const metrics: BriefMetrics = await request.json();
    const apiKey = process.env.GEMINI_API_KEY?.trim();

    if (!apiKey) {
      return NextResponse.json({
        source: 'fallback',
        requiresReview: true,
        notice:
          'GEMINI_API_KEY is not configured in environment variables. Showing deterministic 30-day executive summary.',
        brief: buildFallbackBrief(metrics),
      });
    }

    const prompt = [
      'You are the municipal tourism analytics assistant for the Municipality of Daet, Camarines Norte (TIA-DAS, Subsystem 10 of CONNECT-DAET.ph).',
      'Write a concise 3-paragraph executive tourism brief for Municipal Tourism Office staff based ONLY on these aggregated 30-day metrics (no personal data):',
      `- Last 30 days arrivals: ${metrics.recentArrivals.toLocaleString()} (Prior 30 days: ${metrics.priorArrivals.toLocaleString()}, Growth: ${metrics.growthRatePct !== null ? `${metrics.growthRatePct}%` : 'N/A'})`,
      `- Top destinations: ${metrics.topDestinations.map((d) => `${d.destination} (${d.total})`).join(', ')}`,
      `- Recorded revenue: PHP ${metrics.totalRevenuePhp.toLocaleString()} (${metrics.verifiedRevenuePct.toFixed(1)}% verified); Employment records: ${metrics.employmentCount}`,
      `- Visitor satisfaction (Subsystem 9): ${metrics.satisfactionScore}/5 across ${metrics.satisfactionCount} ratings`,
      `- Sustainability indicators on Watch/Critical: ${metrics.watchIndicators.length > 0 ? metrics.watchIndicators.join(', ') : 'None'}`,
      'Keep it factual, practical for local government planning, and remind staff that the brief is subject to administrative review.',
    ].join('\n');

    const res = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${encodeURIComponent(apiKey)}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: { temperature: 0.3, maxOutputTokens: 450 },
        }),
      }
    );

    if (!res.ok) {
      return NextResponse.json({
        source: 'fallback',
        requiresReview: true,
        notice: `Gemini API returned HTTP ${res.status}. Showing deterministic 30-day summary instead.`,
        brief: buildFallbackBrief(metrics),
      });
    }

    const json = await res.json();
    const text =
      json?.candidates?.[0]?.content?.parts?.[0]?.text?.trim() ||
      buildFallbackBrief(metrics);

    return NextResponse.json({
      source: 'gemini',
      requiresReview: true,
      notice: 'Generated by Google Gemini from aggregated 30-day metrics. Subject to staff review.',
      brief: text,
    });
  } catch (err) {
    return NextResponse.json(
      {
        source: 'error',
        requiresReview: true,
        notice: err instanceof Error ? err.message : 'Failed to generate brief',
        brief: '',
      },
      { status: 500 }
    );
  }
}

function buildFallbackBrief(m: BriefMetrics): string {
  const growthText =
    m.growthRatePct === null
      ? 'with insufficient prior-period baseline for a 30-day growth comparison'
      : `representing a ${m.growthRatePct >= 0 ? '+' : ''}${m.growthRatePct}% change compared to the prior 30-day window (${m.priorArrivals.toLocaleString()} arrivals)`;

  const topDest =
    m.topDestinations.length > 0
      ? m.topDestinations
          .slice(0, 3)
          .map((d) => `${d.destination} (${d.total.toLocaleString()})`)
          .join(', ')
      : 'no recorded destinations';

  const watchText =
    m.watchIndicators.length > 0
      ? `Attention is advised on sustainability indicators currently marked Watch/Critical: ${m.watchIndicators.join(', ')}.`
      : 'All active sustainability indicators across environmental, economic, social, and governance dimensions are currently on track.';

  return [
    `Over the most recent 30-day period, Daet recorded ${m.recentArrivals.toLocaleString()} tourist arrivals, ${growthText}. Activity was led by ${topDest}.`,
    `Recorded tourism revenue stands at PHP ${m.totalRevenuePhp.toLocaleString()} (${m.verifiedRevenuePct.toFixed(1)}% verified), supporting ${m.employmentCount.toLocaleString()} reported tourism jobs. Visitor satisfaction from Subsystem 9 averages ${m.satisfactionScore}/5 across ${m.satisfactionCount} valid ratings.`,
    `${watchText} Note: This brief is based on aggregated records and is subject to Municipal Tourism Office staff review before formal reporting.`,
  ].join('\n\n');
}
